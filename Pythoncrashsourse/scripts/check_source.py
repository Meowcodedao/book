#!/usr/bin/env python3
"""Check the extracted English Markdown against the PDF extraction.

1. Code check: every fenced block labelled with a .py filename is parsed with
   Python's `ast` (also tried as an excerpt from inside a function/method). A failure usually means broken indentation (the most
   dangerous extraction error). Blocks that are deliberately partial
   (containing "--snip--", "...", a Python 2 print statement) are reported
   separately as "partial".
2. Coverage check: all words of each PDF page range (minus running heads and
   page numbers) must appear in the unit's Markdown, and vice versa.

Usage:
    python3 scripts/check_source.py [slug ...]
Output:
    qa/source-check.md
"""
import ast
import json
import re
import sys
import textwrap
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
from mdcode import code_blocks, strip_gutter  # noqa: E402

FOOTER_Y = 630


def words(text):
    # hyphens are ignored on both sides: "tech-nologies" == "technologies"
    text = re.sub(r"(?<=[A-Za-z])[-\xad]\s*(?=[A-Za-z])", "", text.replace("\xad", "-"))
    return Counter(w.lower() for w in re.findall(r"[A-Za-z0-9]+", text))


def pdf_words(pages, start, end):
    lines = []
    for p in pages[start - 1:end]:
        for b in p["blocks"]:
            for ln in b:
                if ln[0]["y"] > FOOTER_Y:
                    continue
                lines.append("".join(s["text"] for s in ln
                                     if s["font"] not in ("Wingdings2", "Webdings", "Symbol", "DogmaBold")
                                     and s["size"] < 15))
    # join lines so words split by an end-of-line hyphen are rebuilt
    return words("\n".join(l.rstrip() for l in lines))


def md_words(md):
    md = re.sub(r"<!--.*?-->", "", md)
    md = re.sub(r"^# .*$", "", md, count=1, flags=re.M)   # H1 comes from the outline
    md = md.replace("**Try It Yourself**", "")           # box title / note label: DogmaBold, skipped in PDF
    md = md.replace("> **Note**", "")
    md = re.sub(r"^```\w*$", "", md, flags=re.M)         # fence language tags
    return words(md)


def parses(code):
    """True if the block is valid Python, possibly as an excerpt of a method body."""
    for candidate in (code, textwrap.dedent(code),
                      "class _A:\n    def _f(self):\n" + code,       # excerpt from a method
                      "def _f():\n" + textwrap.indent(textwrap.dedent(code), "    ")):
        try:
            ast.parse(candidate)
            return True
        except SyntaxError:
            pass
    return False


def main():
    units = json.loads((ROOT / "original" / "units.json").read_text(encoding="utf-8"))
    pages = [json.loads(l) for l in open(ROOT / "original" / "extracted" / "pages.jsonl", encoding="utf-8")]
    only = set(sys.argv[1:])
    report = ["# Source extraction check", "",
              "Generated by `scripts/check_source.py`. English source only (`original/chapters/`).", ""]
    summary = ["| Unit | .py blocks | parse OK (incl. excerpts) | partial | FAILED | words missing | words extra |",
               "|---|---|---|---|---|---|---|"]
    details = []
    for u in units["units"]:
        if only and u["slug"] not in only:
            continue
        md = (ROOT / "original" / "chapters" / f"{u['slug']}.md").read_text(encoding="utf-8")
        n = ok = partial = 0
        fails = []
        for blk in code_blocks(md):
            if not blk["label"].endswith(".py"):
                continue
            n += 1
            code = strip_gutter(blk["code"])
            if parses(code):
                ok += 1
                continue
            try:
                ast.parse(code)
            except SyntaxError as e:
                if re.search(r"--snip--|\.\.\.|^\s*print [\"'a-z]", code, re.M):
                    partial += 1
                else:
                    fails.append(f"- `{blk['label']}` (line {blk['line']} of md): {e.msg} at code line {e.lineno}")
        a, b = pdf_words(pages, u["start"], u["end"]), md_words(md)
        missing, extra = a - b, b - a
        summary.append(f"| {u['slug']} | {n} | {ok} | {partial} | {len(fails)} | "
                       f"{sum(missing.values())} | {sum(extra.values())} |")
        if fails or missing or extra:
            details.append(f"## {u['slug']}\n")
            details.extend(fails)
            if missing:
                details.append("\nMissing from Markdown: " + ", ".join(f"{w}×{k}" for w, k in missing.most_common(30)))
            if extra:
                details.append("\nExtra in Markdown: " + ", ".join(f"{w}×{k}" for w, k in extra.most_common(30)))
            details.append("")
    out = ROOT / "qa" / "source-check.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(report + summary + ["", "# Details", ""] + details) + "\n", encoding="utf-8")
    print("\n".join(summary))
    print(f"-> {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
